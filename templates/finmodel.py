#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Финансовая модель инициативы: NPV, окупаемость, сценарии, Монте-Карло, безубыточность.

Заготовка для агента: меняются только значения в блоке ДОПУЩЕНИЯ ниже,
остальное считается само. Уровень детализации — такой, чтобы руководитель
мог пересчитать модель в ходе обсуждения на правлении.

Три правила модели (см. AGENTS.md, раздел 8):
  1. Эффекты берутся по КОНСЕРВАТИВНОЙ границе коридора (A4).
  2. Небюджетируемые эффекты в модель не идут: высвобожденные часы, которые
     не приводят ни к сокращению затрат, ни к появлению нового результата,
     экономией не являются.
  3. Сопровождение — отдельной строкой, 15–30 % стоимости внедрения в год.

Запуск:
    python3 finmodel.py                # расчёт и текстовый отчёт
    python3 finmodel.py --chart out.png  # плюс гистограмма распределения NPV

Зависимости: numpy (обязательно), matplotlib (только для --chart).
"""

import argparse

try:
    import numpy as np
except ImportError:  # pragma: no cover
    raise SystemExit("Нужен numpy:  pip install numpy")


# ══════════════════════════════════════════════════════════════════════
# ДОПУЩЕНИЯ — единственный блок, который правит агент
# ══════════════════════════════════════════════════════════════════════

ИНИЦИАТИВА = "Предпроектная проработка инициатив регионов"
ТИП = "проектная"

# Каждое допущение: (значение, единица, метка достоверности, основание)
# Метки: БЕНЧМАРК — подтверждено измерением · АНАЛОГ — перенос из смежного случая
#        ГИПОТЕЗА — оценка с погрешностью до 50 %
ДОПУЩЕНИЯ = {
    "заявок_в_год":        (240,    "шт.",     "БЕНЧМАРК", "текущий объём; рост не закладываем"),
    "часов_было":          (60,     "ч/заявка", "БЕНЧМАРК", "замер по 12 заявкам 2025 г."),
    "часов_стало":         (34,     "ч/заявка", "БЕНЧМАРК", "минимум коридора A4 — слабейший подтверждённый эффект"),
    "стоимость_часа":      (2_800,  "₽/ч",     "БЕНЧМАРК", "полная стоимость часа аналитика"),
    "внедрение":           (12_000_000, "₽",   "АНАЛОГ",   "сопоставимая интеграция, 2 подрядчика"),
    "доля_сопровождения":  (0.20,   "доля",    "АНАЛОГ",   "20 % от внедрения в год"),
    "ставка":              (0.20,   "доля",    "ГИПОТЕЗА", "ставка дисконтирования организации"),
    "горизонт_лет":        (3,      "лет",     "—",        "горизонт модели"),
    "выход_на_режим":      (0.6,    "доля",    "ГИПОТЕЗА", "доля эффекта в первый год"),
}

# Качественные эффекты — НЕ бюджетируемые, в расчёт не идут, но называются на защите
КАЧЕСТВЕННЫЕ_ЭФФЕКТЫ = [
    "Снятие очереди: регион получает ответ в предсказуемый срок",
    "Единый формат концепции — сопоставимость заявок между собой",
]

# Сценарный разброс: имя → (консервативно, базово, оптимистично).
# Порядок — по ВЛИЯНИЮ НА РЕЗУЛЬТАТ, а не по величине: для «часов_стало»
# и «внедрение» меньшее значение лучше. Среднее значение обязано совпадать
# с базовым допущением выше — иначе сценарии разъедутся с моделью.
# Консервативная граница может лежать за пределами подтверждённого коридора:
# это стресс-проверка «эффект оказался вдвое слабее заявленного».
РАЗБРОС = {
    "заявок_в_год":  (240,        240,        400),
    "часов_стало":   (48,         34,         24),
    "внедрение":     (18_000_000, 12_000_000,  9_000_000),
}


# ══════════════════════════════════════════════════════════════════════
# РАСЧЁТ
# ══════════════════════════════════════════════════════════════════════

def значение(имя, переопределения=None):
    if переопределения and имя in переопределения:
        return переопределения[имя]
    return ДОПУЩЕНИЯ[имя][0]


def годовой_эффект(п=None):
    """Экономия в рублях за полный год работы."""
    заявок = значение("заявок_в_год", п)
    было = значение("часов_было", п)
    стало = значение("часов_стало", п)
    час = значение("стоимость_часа", п)
    return заявок * (было - стало) * час


def денежный_поток(п=None):
    """Поток по годам 0..N. Год 0 — внедрение."""
    лет = int(значение("горизонт_лет", п))
    внедрение = значение("внедрение", п)
    сопровождение = внедрение * значение("доля_сопровождения", п)
    выход = значение("выход_на_режим", п)
    эффект = годовой_эффект(п)

    поток = [-внедрение]
    for год in range(1, лет + 1):
        доля = выход if год == 1 else 1.0
        поток.append(эффект * доля - сопровождение)
    return поток


def npv(поток, ставка):
    return sum(cf / (1 + ставка) ** i for i, cf in enumerate(поток))


def окупаемость_мес(поток):
    """Простой срок окупаемости в месяцах с линейной интерполяцией внутри года."""
    накоплено = поток[0]
    if накоплено >= 0:
        return 0
    for год in range(1, len(поток)):
        if поток[год] <= 0:
            накоплено += поток[год]
            continue
        if накоплено + поток[год] >= 0:
            доля_года = -накоплено / поток[год]
            return round((год - 1 + доля_года) * 12)
        накоплено += поток[год]
    return None  # не окупается на горизонте модели


def сценарий(имя, п):
    поток = денежный_поток(п)
    v = npv(поток, значение("ставка", п))
    м = окупаемость_мес(поток)
    return {"имя": имя, "поток": поток, "npv": v, "окупаемость": м}


def безубыточность(параметр, лево, право, шаг=200):
    """Значение параметра, при котором NPV обращается в ноль (бинарный поиск)."""
    def f(x):
        return npv(денежный_поток({параметр: x}), значение("ставка"))

    a, b = min(лево, право), max(лево, право)
    if f(a) * f(b) > 0:
        return None
    for _ in range(шаг):
        m = (a + b) / 2
        if f(a) * f(m) <= 0:
            b = m
        else:
            a = m
    return (a + b) / 2


def монте_карло(итераций=5000, seed=42):
    """Треугольное распределение по границам коридора эффекта."""
    rng = np.random.default_rng(seed)
    выборки = {}
    for имя, границы in РАЗБРОС.items():
        # границы заданы по влиянию на результат, а не по величине — сортируем
        лево, мода, право = min(границы), границы[1], max(границы)
        выборки[имя] = rng.triangular(лево, мода, право, итераций)

    результат = np.empty(итераций)
    ставка = значение("ставка")
    for i in range(итераций):
        п = {имя: выборки[имя][i] for имя in выборки}
        результат[i] = npv(денежный_поток(п), ставка)
    return результат


# ══════════════════════════════════════════════════════════════════════
# ОТЧЁТ
# ══════════════════════════════════════════════════════════════════════

def млн(x):
    return f"{x / 1_000_000:+.1f} млн ₽"


def отчёт(chart=None):
    print("═" * 68)
    print(f"ФИНАНСОВАЯ МОДЕЛЬ · {ИНИЦИАТИВА}")
    print(f"Тип инициативы: {ТИП}")
    print("═" * 68)

    print("\n1. РЕЕСТР ДОПУЩЕНИЙ")
    print(f"{'допущение':<22}{'значение':>16}  {'ед.':<10}{'метка':<10}основание")
    print("-" * 68)
    for имя, (знач, ед, метка, основание) in ДОПУЩЕНИЯ.items():
        показ = f"{знач:,.0f}".replace(",", " ") if знач >= 100 else f"{знач}"
        print(f"{имя:<22}{показ:>16}  {ед:<10}{метка:<10}{основание}")

    print("\n2. ДЕНЕЖНЫЙ ПОТОК")
    базовый = сценарий("базовый", None)
    print(f"годовой эффект на полном режиме: {годовой_эффект():,.0f} ₽".replace(",", " "))
    for год, cf in enumerate(базовый["поток"]):
        print(f"  год {год}: {cf:>16,.0f} ₽".replace(",", " "))
    print(f"\nNPV (ставка {значение('ставка'):.0%}): {млн(базовый['npv'])}")
    print(f"Срок окупаемости: {базовый['окупаемость']} мес"
          if базовый["окупаемость"] is not None else "Не окупается на горизонте модели")

    print("\n3. СЦЕНАРИИ")
    # РАЗБРОС хранит границы уже в порядке (консервативно, базово, оптимистично),
    # поэтому сценарий — это срез по индексу, без исключений для отдельных параметров.
    сценарии = [
        сценарий("консервативный", {имя: гр[0] for имя, гр in РАЗБРОС.items()}),
        базовый,
        сценарий("оптимистичный", {имя: гр[2] for имя, гр in РАЗБРОС.items()}),
    ]
    print(f"{'сценарий':<18}{'NPV':>16}{'окупаемость':>16}")
    print("-" * 50)
    for с in сценарии:
        ок = f"{с['окупаемость']} мес" if с["окупаемость"] is not None else "нет"
        print(f"{с['имя']:<18}{млн(с['npv']):>16}{ок:>16}")

    print("\n4. МОНТЕ-КАРЛО (5000 прогонов, треугольное распределение)")
    выборка = монте_карло()
    p10, p50, p90 = np.percentile(выборка, [10, 50, 90])
    доля = float((выборка > 0).mean())
    print(f"  P10: {млн(p10)}")
    print(f"  P50: {млн(p50)}")
    print(f"  P90: {млн(p90)}")
    print(f"  вероятность NPV > 0: {доля:.0%}")

    print("\n5. ГРАНИЦЫ БЕЗУБЫТОЧНОСТИ")
    for параметр, границы in РАЗБРОС.items():
        нижняя, верхняя = min(границы), max(границы)
        точка = безубыточность(параметр, нижняя * 0.2, верхняя * 3)
        if точка is None:
            print(f"  {параметр}: NPV не обращается в ноль в разумном диапазоне")
        else:
            знач, ед = ДОПУЩЕНИЯ[параметр][0], ДОПУЩЕНИЯ[параметр][1]
            направление = "опускается ниже" if точка < знач else "поднимается выше"
            число = f"{точка:,.0f}".replace(",", " ")
            print(f"  инициатива перестаёт окупаться, если «{параметр}» "
                  f"{направление} {число} {ед}")

    print("\n6. КАЧЕСТВЕННЫЕ ЭФФЕКТЫ (в модель не заложены)")
    for э in КАЧЕСТВЕННЫЕ_ЭФФЕКТЫ:
        print(f"  · {э}")

    print("\n" + "═" * 68)
    вывод = ("инициатива окупается в базовом сценарии"
             if базовый["npv"] > 0 else "инициатива не окупается в базовом сценарии")
    print(f"ВЫВОД: {вывод}; вероятность положительного NPV — {доля:.0%}. "
          f"\nЭффекты заложены по консервативной границе коридора; "
          f"сопровождение учтено отдельной строкой.")
    print("═" * 68)

    if chart:
        построить_график(выборка, chart)


def построить_график(выборка, путь):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("\n[matplotlib не установлен — график пропущен]")
        return
    p10, p50, p90 = np.percentile(выборка, [10, 50, 90])
    fig, ax = plt.subplots(figsize=(9, 4.6))
    ax.hist(выборка / 1_000_000, bins=60, color="#ff5533", alpha=.85, edgecolor="none")
    for знач, подпись, стиль in ((p10, "P10", ":"), (p50, "P50", "-"), (p90, "P90", ":")):
        ax.axvline(знач / 1_000_000, color="#1e2027", linestyle=стиль, linewidth=1.6)
        ax.text(знач / 1_000_000, ax.get_ylim()[1] * .94, f" {подпись}", fontsize=9)
    ax.axvline(0, color="#888", linewidth=1)
    ax.set_xlabel("NPV, млн ₽")
    ax.set_ylabel("частота")
    ax.set_title(f"Распределение NPV · {ИНИЦИАТИВА}", fontsize=11)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(путь, dpi=150)
    print(f"\nГрафик сохранён: {путь}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="Финансовая модель инициативы")
    ap.add_argument("--chart", metavar="PNG", help="сохранить гистограмму распределения NPV")
    args = ap.parse_args()
    отчёт(args.chart)
